"""Защитные фильтры: имена, «палево» про ИИ, служебные формулировки.

Ничего не отправляется клиенту, если ответ не прошёл проверку. Вместо этого он идёт тебе.
"""
import os
import re

# Слова/основы, которые вообще нельзя произносить и обсуждать (через запятую, в нижнем регистре).
# Можно расширить переменной окружения FORBIDDEN_WORDS, например: "галин,имя2"
FORBIDDEN_WORDS = [
    w.strip().lower().replace("ё", "е")
    for w in os.getenv("FORBIDDEN_WORDS", "галин").split(",")
    if w.strip()
]

# Основы распространённых имён: бот не должен называть НИКОГО по имени.
NAME_STEMS = """
александр алексей анатол андре антон аркад арсен артем артур борис вадим валер василий виктор виталий
владимир владислав вячеслав геннад георг григор даниил денис дмитр евген егор иван игорь илья кирилл
константин леонид максим михаил никита николай олег павел петр роман руслан сергей станислав степан
тимур федор юрий ярослав айбек бакыт нурлан азамат эрлан мирлан данияр адилет марат бекзат улан
эльдар рустам ринат ильяс самат
александра алина алла анастаси ангелина анна анжела валентина валери варвар виктория галин дарья диана
евгени екатерин елен елизавет зарина инна ирин карина кристин ксени лариса лидия лилия людмил маргарит
марина мария милена наталь наргиз нина оксан ольг полина раиса регина светлан снежана софия татьяна
тамара ульяна юлия яна айгерим айгуль айнура гульнара жанна мээрим нургуль динара айжан бермет
чолпон салтанат асель эльвира жибек
""".split()

# Обычные слова, начинающиеся как имя.
NAME_EXCLUDE = {"максимум", "максимума", "максимуму", "маринад", "маринады"}

WORD = re.compile(r"[a-zа-я0-9]+", re.I)


def norm(s: str) -> str:
    return s.lower().replace("ё", "е")


def mentions_name(text: str, extra_tokens=()) -> str | None:
    extra = {norm(t) for t in extra_tokens}
    for t in WORD.findall(norm(text)):
        if t in NAME_EXCLUDE:
            continue
        if t in extra:
            return t
        for s in NAME_STEMS:
            if t.startswith(s) and len(t) <= len(s) + 3:
                return t
    return None


def mentions_forbidden(text: str) -> str | None:
    n = norm(text)
    for w in FORBIDDEN_WORDS:
        if w in n:
            return w
    return None


# ---- что клиент спрашивает: такие сообщения бот сам не отправляет, а передаёт тебе ----
NAME_ASK = re.compile(
    r"как\s+(вас|тебя|к\s+вам|к\s+тебе)\s+(зовут|называть|обращаться)|как\s+зовут|ваше\s+имя|твое\s+имя"
    r"|ваше\s+фио|представьтесь|представься|кто\s+(вы|ты)\b|с\s+кем\s+(я\s+)?(общаюсь|говорю|разговариваю|переписываюсь)"
    r"|(ваша|твоя)\s+фамилия|как\s+вас\s+величать"
)
AI_ASK = re.compile(
    r"\b(вы|ты|вас|тебя|вами|тобой)\b[^.?!\n]{0,25}\b(бот\w*|робот\w*|нейросет\w*|искусственн\w+|ии|ai|chatgpt|чатгпт|гпт)\b"
    r"|(живой|настоящий|реальный)\s+(человек|менеджер|сотрудник)|автоответ\w*|человек\s+или\s+(бот|робот|ии)"
    r"|(это|тут|там)\s+(бот|робот|ии|нейросет\w*)\s*\?"
)
ATTACH_ONLY = re.compile(r"^(\[вложение[^\]]*\]\s*)+$")


def client_needs_owner(text: str) -> str | None:
    n = norm(text)
    w = mentions_forbidden(n)
    if w:
        return "в сообщении тема, которую бот не обсуждает"
    if NAME_ASK.search(n):
        return "спрашивают имя / кто пишет"
    if AI_ASK.search(n):
        return "спрашивают, бот ли это"
    if ATTACH_ONLY.match(n.strip()):
        return "клиент прислал только вложение (фото/файл/голосовое)"
    return None


# ---- проверка того, что написал бот ----
AI_LEAK = re.compile(
    r"\bкак\s+(ии|ай|искусственн\w+|языков\w+\s+модел\w+|ассистент|бот)\b|\bя\s*[-—–]?\s*(ии|бот|нейросет\w*|ассистент|языков\w+\s+модел\w+)\b"
    r"|чат[-\s]?бот|нейросет|языков\w+\s+модел|искусственн\w+\s+интеллект|\bclaude\b|anthropic|openai|chatgpt|\bgpt\b"
    r"|виртуальн\w+\s+(помощник|ассистент)|\bassistant\b|системн\w+\s+(промпт|инструкц)|мои\s+инструкц|\bescalate\b"
)
REFUSAL = re.compile(
    r"не\s+могу\s+(обсуждать|назвать|говорить|сообщить\s+имя)|мне\s+нельзя|не\s+имею\s+права|не\s+уполномочен"
    r"|к\s+сожалению,?\s+я\s+не\s+могу|извините,?\s+но\s+я|не\s+в\s+моей\s+компетенции|эту\s+тему\s+не"
    r"|чем\s+могу\s+помочь|рад\s+помочь|буду\s+рад|безусловно|разумеется"
)
MAX_REPLY_CHARS = 700


def bad_reply(text: str, client_tokens=()) -> str | None:
    """Возвращает причину, если ответ нельзя отправлять клиенту."""
    n = norm(text)
    if len(text) > MAX_REPLY_CHARS:
        return "слишком длинный ответ"
    w = mentions_forbidden(n)
    if w:
        return f"запрещённое слово «{w}»"
    nm = mentions_name(text, client_tokens)
    if nm:
        return f"в ответе имя «{nm}»"
    if AI_LEAK.search(n):
        return "в ответе палится ИИ / служебные слова"
    if REFUSAL.search(n):
        return "в ответе отказ/шаблонная вежливость, не в моём стиле"
    return None


def sanitize(text: str) -> str:
    """Убираем markdown и лишние пробелы."""
    t = re.sub(r"[*`]+", "", text)
    t = re.sub(r"(?m)^\s*#+\s*", "", t)
    t = re.sub(r"[ \t]+\n", "\n", t)
    return t.strip()


def split_parts(text: str, limit: int = 4) -> list[str]:
    parts = [p.strip() for p in re.split(r"\n\s*---+\s*\n|^\s*---+\s*$", text, flags=re.M) if p.strip()]
    return parts[:limit]


# ---- как реагировать на реплику клиента ----
DEFLECT_HINT = (
    "# Эта реплика клиента\n"
    "Клиент затронул тему имён или людей (кто я, как зовут, чьё-то имя). Эту тему я не поддерживаю. "
    "Ответь в моём стиле коротко и естественно, как будто не придал значения: уведи к делу, переспроси, что нужно по заказу или документам, "
    "или отреагируй одним-двумя словами. Не называй никаких имён, не объясняй, не отказывайся и не говори, что тема закрыта или что-то нельзя. "
    "Тон (не копируй дословно): «а по делу что нужно ?», «щас по документам гляну, что надо», «понял вас, так что по заказу ?», «ааа окей»."
)
ADDRESSED_HINT = (
    "# Эта реплика клиента\n"
    "Клиент обратился ко мне по имени. Отреагируй коротко и живо, как человек, и НЕ повторяй имя: «оу», «да, слушаю», «на связи», «ага слушаю». "
    "Если в сообщении есть вопрос или просьба, сразу ответь по делу."
)


def classify_client(text: str):
    """-> None | ("escalate", причина) | ("deflect", подсказка) | ("addressed", подсказка)"""
    n = norm(text)
    if ATTACH_ONLY.match(n.strip()):
        return "escalate", "клиент прислал только вложение (фото/файл/голосовое)"
    if AI_ASK.search(n):
        return "escalate", "спрашивают, бот ли это"
    if mentions_forbidden(n) or NAME_ASK.search(n):
        return "deflect", DEFLECT_HINT
    if any(t.startswith("адилет") for t in WORD.findall(n)):
        return "addressed", ADDRESSED_HINT
    return None
